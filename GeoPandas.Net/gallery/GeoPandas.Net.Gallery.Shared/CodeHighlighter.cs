using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;
using GeoPandas.Net.Datasets;
using GeoPandas.Net.Raster;
using NetTopologySuite.Geometries;

namespace GeoPandas.Net.Gallery;

public enum TokenKind { Plain, Keyword, Type, String, Number, Comment, Method }

/// <summary>Tiny C# tokenizer for snippet highlighting (shared by the Blazor and Avalonia galleries).</summary>
public static partial class CodeHighlighter
{
    private static readonly HashSet<string> Keywords =
    [
        "var", "new", "using", "await", "async", "return", "foreach", "in", "if", "else", "true", "false", "null", "is", "or", "and",
        "not", "double", "int", "long", "string", "bool", "public", "static", "class", "record", "for", "out", "ref"
    ];

    [GeneratedRegex("""(?<comment>//[^\n]*)|(?<str>"(?:[^"\\]|\\.)*")|(?<num>\b\d[\d_.]*\b)|(?<word>[A-Za-z_][A-Za-z0-9_]*)|(?<other>\s+|.)""")]
    private static partial Regex Lexer();

    public static IEnumerable<(TokenKind Kind, string Text)> Tokenize(string code)
    {
        var matches = Lexer().Matches(code);
        for (int i = 0; i < matches.Count; i++)
        {
            var m = matches[i];
            if (m.Groups["comment"].Success) yield return (TokenKind.Comment, m.Value);
            else if (m.Groups["str"].Success) yield return (TokenKind.String, m.Value);
            else if (m.Groups["num"].Success) yield return (TokenKind.Number, m.Value);
            else if (m.Groups["word"].Success)
            {
                var w = m.Value;
                bool call = i + 1 < matches.Count && matches[i + 1].Value == "(";
                yield return (Keywords.Contains(w) ? TokenKind.Keyword : char.IsUpper(w[0]) && !call ? TokenKind.Type : call ? TokenKind.Method : TokenKind.Plain, w);
            }
            else yield return (TokenKind.Plain, m.Value);
        }
    }
}

/// <summary>Decorative art generated by the library itself.</summary>
public static class GalleryArt
{
    /// <summary>SVG path data of real contour lines from the sample DEM, scaled to a box — used as a subtle header backdrop.</summary>
    public static string ContourPathData(double width, double height, double interval = 60)
    {
        var dem = SampleData.Dem(128, 100);
        var contours = dem.Contours(interval);
        var env = dem.Bounds;
        double sx = width / env.Width, sy = height / env.Height, s = Math.Max(sx, sy);
        var sb = new StringBuilder();
        foreach (var g in contours.Geometry)
        {
            if (g is null) continue;
            for (int i = 0; i < g.NumGeometries; i++)
            {
                if (g.GetGeometryN(i) is not LineString ls) continue;
                var cs = ls.Coordinates;
                for (int k = 0; k < cs.Length; k += 2)
                    sb.Append(k == 0 ? 'M' : 'L')
                      .Append(((cs[k].X - env.MinX) * s).ToString("0.#", CultureInfo.InvariantCulture)).Append(',')
                      .Append(((env.MaxY - cs[k].Y) * s).ToString("0.#", CultureInfo.InvariantCulture));
            }
        }
        return sb.ToString();
    }
}
