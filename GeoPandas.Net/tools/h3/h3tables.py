"""Extracts H3's numeric tables from the reference C sources (uber/h3 v4.1.0, Apache-2.0) into flat C# arrays."""
import re, sys, os
src = sys.argv[1]; out = sys.argv[2]
SYMBOLS = {
    'CENTER_DIGIT': '0', 'K_AXES_DIGIT': '1', 'J_AXES_DIGIT': '2', 'JK_AXES_DIGIT': '3', 'I_AXES_DIGIT': '4',
    'IK_AXES_DIGIT': '5', 'IJ_AXES_DIGIT': '6', 'INVALID_DIGIT': '7', 'INVALID_BASE_CELL': '127',
    'IJ': '1', 'KI': '2', 'JK': '3', 'INVALID_FACE': '-1',
}
TABLES = [  # (file, C name, C# name, C# type)
    ('faceijk.c', 'faceCenterGeo', 'FaceCenterGeo', 'double'),
    ('faceijk.c', 'faceCenterPoint', 'FaceCenterPoint', 'double'),
    ('faceijk.c', 'faceAxesAzRadsCII', 'FaceAxesAzRadsCII', 'double'),
    ('faceijk.c', 'faceNeighbors', 'FaceNeighbors', 'int'),
    ('faceijk.c', 'adjacentFaceDir', 'AdjacentFaceDir', 'int'),
    ('faceijk.c', 'maxDimByCIIres', 'MaxDimByCIIres', 'int'),
    ('faceijk.c', 'unitScaleByCIIres', 'UnitScaleByCIIres', 'int'),
    ('baseCells.c', 'baseCellNeighbors', 'BaseCellNeighbors', 'int'),
    ('baseCells.c', 'baseCellNeighbor60CCWRots', 'BaseCellNeighbor60CCWRots', 'int'),
    ('baseCells.c', 'faceIjkBaseCells', 'FaceIjkBaseCells', 'int'),
    ('baseCells.c', 'baseCellData', 'BaseCellData', 'int'),
    ('algos.c', 'NEW_DIGIT_II', 'NewDigitII', 'int'),
    ('algos.c', 'NEW_ADJUSTMENT_II', 'NewAdjustmentII', 'int'),
    ('algos.c', 'NEW_DIGIT_III', 'NewDigitIII', 'int'),
    ('algos.c', 'NEW_ADJUSTMENT_III', 'NewAdjustmentIII', 'int'),
]
def strip_comments(s):
    s = re.sub(r'/\*.*?\*/', ' ', s, flags=re.S)
    return re.sub(r'//[^\n]*', ' ', s)
lines = ['// <auto-generated> H3 lookup tables, extracted from uber/h3 v4.1.0 (Apache License 2.0, https://github.com/uber/h3) by tools/h3/h3tables.py. </auto-generated>',
         'namespace GeoPandas.Net.Geometry.Index;', '', 'internal static partial class H3Tables', '{']
for fname, cname, csname, typ in TABLES:
    text = strip_comments(open(os.path.join(src, fname), encoding='utf-8').read())
    m = re.search(r'\b' + re.escape(cname) + r'\s*(\[[^=]*\])?\s*=\s*\{', text)
    if not m: raise SystemExit(f'{cname} not found')
    i = m.end() - 1; depth = 0
    for j in range(i, len(text)):
        if text[j] == '{': depth += 1
        elif text[j] == '}':
            depth -= 1
            if depth == 0: body = text[i + 1:j]; break
    toks = re.findall(r'[A-Za-z_][A-Za-z_0-9]*|-?\d+\.\d*(?:[eE][-+]?\d+)?L?|-?\d+(?:[eE][-+]?\d+)?L?|-?\.\d+', body)
    vals = []
    for t in toks:
        if t in SYMBOLS: vals.append(SYMBOLS[t])
        elif re.match(r'^-?[\d.]', t): vals.append(t.rstrip('L'))
        else: raise SystemExit(f'unknown symbol {t} in {cname}')
    if typ == 'double': vals = [v if ('.' in v or 'e' in v.lower()) else v + '.0' for v in vals]
    lines.append(f'    // {cname}: {len(vals)} values')
    lines.append(f'    internal static readonly {typ}[] {csname} =')
    lines.append('    [')
    for k in range(0, len(vals), 12): lines.append('        ' + ', '.join(vals[k:k + 12]) + ',')
    lines.append('    ];')
    print(cname, len(vals))
lines.append('}')
open(out, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
